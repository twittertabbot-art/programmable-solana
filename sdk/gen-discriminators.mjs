// Regenerates src/generated.ts. Run after adding or renaming an instruction, account or event:
//   node gen-discriminators.mjs
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const d = (s) => "[" + [...createHash("sha256").update(s).digest().subarray(0, 8)].join(", ") + "]";

const ix = {
  hookpool: ["init_platform", "update_platform", "set_whitelist", "transfer_admin", "accept_admin", "create_pool", "add_liquidity", "remove_liquidity", "swap", "hook_swap", "collect_protocol_fees", "collect_hook_fees", "hook_buy_burn",
    // the curve
    "create_curve_pool", "graduate",
    // the approved list
    "approve_hook", "revoke_hook"],
  hooklaunch: ["create_token", "create_pegged_mint", "finish_pegged_token", "launch", "launch_curve"],
  hook_tax: ["init_manifest", "init_pool_config", "set_tax", "set_owner"],
  hook_launch_guard: ["init_manifest", "init_pool_config"],
  hook_buyback: ["init_manifest", "init_pool_config", "execute_buyback"],
  hook_collectible: ["init_manifest", "init_pool_config", "open_ticket", "open_ticket_for", "init_peg", "reveal", "mint", "settle", "reorder", "send_pieces", "stage", "deliver", "reap", "update_collection", "set_owner",
    // round 8: one approval
    "mint_for", "withdraw_deposit"],
  hook_rules: ["init_manifest", "init_pool_config", "stake", "unstake", "claim_rewards", "claim_creator", "run_burn", "lock_creator", "unlock_creator",
    // strict coin
    "init_strict_config", "open_holder", "claim_holder", "sync_holder", "close_holder", "lock_creator_strict", "unlock_creator_strict", "run_burn_strict"],
};
const accounts = ["Platform", "Pool", "TaxConfig", "GuardConfig", "BuybackConfig", "Launch", "HookManifest", "CollectionConfig", "Ticket", "BurnQueue", "RulesConfig", "StakeRecord", "LockRecord", "HolderRecord"];
const events = [
  "PoolCreated", "Swapped", "LiquidityChanged", "PlatformUpdated", "ProtocolFeesCollected", "HookFeesCollected", "TokenCreated", "Launched", "BuybackExecuted", "PiecesEarned", "BatchRevealed", "PieceMinted", "PiecesCancelled", "PieceBurned", "PieceSent", "PiecesTransferred", "PieceDelivered", "CollectionUpdated", "DepositUsed", "DepositWithdrawn",
  // hook_rules
  "BurnExecuted", "Staked", "Unstaked", "RewardsClaimed", "CreatorClaimed", "CreatorLocked", "CreatorUnlocked",
  "HolderOpened", "HolderClaimed", "HolderSynced", "HolderClosed",
  // the curve (hookpool)
  "CurveOpened", "Graduated",
  // the approved list (hookpool)
  "HookApprovalChanged", "HookApprovalRequiredChanged",
];

let out = "// GENERATED by gen-discriminators.mjs. Discriminators are sha256(prefix:name)[0..8].\n";
out += '// Instruction = "global:<snake_name>", account = "account:<Name>", event = "event:<Name>".\n\n';
out += "export const IX: Record<string, Record<string, number[]>> = {\n";
for (const [p, names] of Object.entries(ix)) {
  out += `  ${p}: {\n`;
  for (const n of names) out += `    ${n}: ${d("global:" + n)},\n`;
  out += "  },\n";
}
out += "};\n\nexport const ACCOUNT_DISC: Record<string, number[]> = {\n";
for (const a of accounts) out += `  ${a}: ${d("account:" + a)},\n`;
out += "};\n\nexport const EVENT_DISC: Record<string, number[]> = {\n";
for (const e of events) out += `  ${e}: ${d("event:" + e)},\n`;
out += "};\n\nexport const CALLBACK_TLV_DISC = " + d("hookpool-interface:callback") + ";\n";
writeFileSync(new URL("./src/generated.ts", import.meta.url), out);
console.log("src/generated.ts written");
